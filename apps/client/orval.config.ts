import { fileURLToPath } from 'node:url';
import { defineConfig } from 'orval';
import { loadEnv } from 'vite';

const clientRoot = fileURLToPath(new URL('.', import.meta.url));
const env = loadEnv('dev', clientRoot, '');
const apiBaseUrl = env.VITE_API_BASE_URL ?? '/api/v1';
const proxyTarget = env.VITE_PROXY_TARGET?.replace(/\/+$/, '');

const openApiTarget =
  env.ORVAL_OPENAPI_URL ??
  (apiBaseUrl.startsWith('http')
    ? `${apiBaseUrl}/openapi.json`
    : `${proxyTarget ?? 'http://127.0.0.1:5173'}${apiBaseUrl}/openapi.json`);

export default defineConfig({
  miningManager: {
    input: {
      target: openApiTarget,
    },
    output: {
      client: 'react-query',
      httpClient: 'axios',
      mode: 'split',
      target: './src/api/generated',
      schemas: './src/api/generated/model',
      clean: true,
      override: {
        mutator: {
          path: './src/api/mutator/customInstance.ts',
          name: 'customInstance',
        },
        query: {
          useSuspenseQuery: false,
        },
        header: () => [
          'Generated by Orval from the Mining Manager OpenAPI spec.',
          'Do not edit manually.',
        ],
      },
    },
  },
});
